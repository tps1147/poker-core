// THE FILMS' CARD WIPES (2026-10-18, Tyler: "the end video transitions are still broken on the video
// end with the card flipping"). Every lesson film ends by sweeping a giant card back across the
// frame and flipping it into its own "up next" card, starting about half a second before its upNext
// anchor; a few sweep one in earlier too, into the rule card their "Up next" line is spoken over. A
// watch must never stop, ask or hand off inside one (filmV2 filmStop, filmAskPlan). FILM_SPEECH
// `motion` is measured coarsely (54 x 96, a change of 2 or more) and misses the first frames of a
// wipe, when the card comes in edge-on as a sliver: this measures them on the published picture at
// 135 x 240. Writes src/learn/filmEnds.mjs (generated: never edit it by hand; rerun whenever a film
// is re-cut, the filmV2 test fails on a stale version).
//
// Per lesson film (node id): `at` its upNext anchor; `wipes` [[still, end]] for every wipe in the
// LOOK seconds up to `at` (and moving at it): a run of moving frames (each a change over STILL) that
// changes by WIPE_IN or more somewhere. `still` is the middle of the frame before the last still one
// ahead of it (a frame in hand), found by walking back from its first big change while the picture
// still moves and the change keeps rising, or stays above RISING (the sliver's first jump can be
// larger than the next frame's); `end` the middle of its last moving frame.
//
//   node scripts/sync-film-ends.mjs [publishDir]   (or FILMS_V2_PUBLISH; default: the Codex motion draft)
// Needs ffmpeg on the PATH.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { NODES } from "../src/learn/academyTree.mjs";
import { canon } from "../src/learn/filmV2.mjs";

const DEFAULT = "C:/Users/tps11/Documents/Codex/2026-10-05/task-5/claude-motion-draft-2026-10-06/publish/films-v2";
const from = process.argv[2] || process.env.FILMS_V2_PUBLISH || DEFAULT;
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const FPS = 30;
const W = 135;
const H = 240;
const LOOK = 6;
const WIPE_IN = 8;
const STILL = 0.15;
const RISING = 1;
const r3 = (v) => Math.round(v * 1000) / 1000;

function grey(video, k0, count) {
  const size = W * H;
  const buf = execFileSync("ffmpeg", ["-v", "error", "-ss", (k0 / FPS).toFixed(4), "-i", video, "-frames:v", String(count),
    "-vf", `scale=${W}:${H},format=gray`, "-f", "rawvideo", "-"], { maxBuffer: 1 << 28 });
  return { n: Math.floor(buf.length / size), at: (i) => buf.subarray(i * size, (i + 1) * size) };
}
const change = (a, b) => { let sum = 0; for (let p = 0; p < a.length; p += 1) sum += Math.abs(a[p] - b[p]); return sum / a.length; };

const out = {};
const missing = [];
for (const node of NODES) {
  const id = node.id;
  const mediaPath = join(root, "src", "learn", "media", `${id}.v3.json`);
  if (!existsSync(mediaPath)) { missing.push(id); continue; }
  const media = JSON.parse(readFileSync(mediaPath, "utf8"));
  const c = canon(media);
  const at = c.anchors.upNext ?? c.duration;
  if (at == null) continue;
  let video = join(from, id, String(media.version), `${id}-1080.mp4`);
  if (!existsSync(video)) video = join(from, id, String(media.version), `${id}-720.mp4`);
  if (!existsSync(video)) { missing.push(id); continue; }
  const k0 = Math.max(1, Math.floor((at - LOOK) * FPS) - 1);
  const kAt = Math.floor(at * FPS);
  const read = grey(video, k0, kAt - k0 + 2);
  const d = [];
  for (let i = 1; i < read.n; i += 1) d[i] = change(read.at(i - 1), read.at(i));
  // d[i]: the picture moving into frame k0 + i. A wipe: a run of moving frames that changes by
  // WIPE_IN or more somewhere; it starts at its leading edge (walked back from its first big change
  // while still moving and rising, or above RISING) and ends at its last moving frame.
  const last = Math.min(read.n - 1, kAt - k0 + 1);
  const wipes = [];
  for (let i = 1; i <= last; i += 1) {
    if (!(d[i] >= WIPE_IN)) continue;
    let j = i;
    while (j > 1 && d[j - 1] > STILL && (d[j - 1] < d[j] || d[j - 1] > RISING)) j -= 1;
    let e = i;
    while (e + 1 < read.n && d[e + 1] > STILL) e += 1;
    // Frame k0 + j is the first that moved; the one before it is the last still frame. The stop
    // keeps a frame in hand (a decoder that shows the frame after the seek point still shows a
    // still one): the middle of the frame before that.
    wipes.push([r3((k0 + j - 2 + 0.5) / FPS), r3((k0 + e + 0.5) / FPS)]);
    i = e;
  }
  out[id] = { version: media.version || null, at: r3(at), wipes };
}

const body = Object.keys(out).sort().map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(out[id])},`).join("\n");
writeFileSync(join(root, "src", "learn", "filmEnds.mjs"), `// GENERATED by scripts/sync-film-ends.mjs from the films' published pictures: do not edit by hand.
// Per lesson film (node id): the v3 media version it was measured for; \`at\`, its upNext anchor
// (seconds); \`wipes\`, [still, end] for each card wipe up to it: the frame to rest on ahead of the
// wipe and its last moving frame. The script says how each is measured.
export const FILM_ENDS = Object.freeze({
${body}
});
`);
console.log(`sync-film-ends: ${Object.keys(out).length} films${missing.length ? `; missing ${missing.join(", ")}` : ""}`);
if (missing.length) process.exit(1);
